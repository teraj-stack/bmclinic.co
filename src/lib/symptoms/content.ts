export const symptomContent: Record<Specialty, SymptomContent> = {
  proktologia: proctology,
  flebologia: phlebology,
};
export function findTopic(
  content: SymptomContent,
  id: string,
): Topic | undefined {
  return content.groups.flatMap((g) => g.topics).find((t) => t.id === id);
}
