function group(
  index: number,
  title: string,
  description: string,
  entries: Entry[],
): TopicGroup {
  return {
    title,
    description,
    topics: entries.map(([id, label, text, timing, features, prepare]) => ({
      id,
      label,
      description: text,
      timing,
      features,
      prepare,
      group: index,
    })),
  };
}
